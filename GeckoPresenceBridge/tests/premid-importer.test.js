import test from 'node:test';
import assert from 'node:assert/strict';
import { compilePreMiDSource } from '../scripts/import-premid-activities.mjs';
import { readFile } from 'node:fs/promises';

test('compiles a PreMiD activity into an isolated global compatibility wrapper', () => {
  const source = `import { ActivityType, Assets, getTimestamps } from 'premid';\nconst presence = new Presence({ clientId: 'ignored-by-gpb' });\npresence.on('UpdateData', () => presence.setActivity({ type: ActivityType.Watching, details: 'Example', smallImageKey: Assets.Play }));`;
  const output = compilePreMiDSource(source, 'example/presence.ts');
  assert.match(output, /globalThis\.Presence/);
  assert.match(output, /globalThis\.__gpbPreMiDCompatV1\.presence/);
  assert.match(output, /const Presence = globalThis\.Presence/);
  assert.match(output, /presence\.setActivity/);
  assert.doesNotMatch(output, /from ['"]premid['"]/);
});

test('refuses imported activity code that attempts arbitrary network access', () => {
  assert.throws(() => compilePreMiDSource(`const presence = new Presence({clientId:'x'}); fetch('https://tracker.invalid');`), /security scan/i);
});

test('compatibility iframe helper enforces imported iframe metadata host patterns', async () => {
  const runtime = await readFile(new URL('../src/content/premid-compat-runtime.ts', import.meta.url), 'utf8');
  assert.match(runtime, /function iframeAllowed\(\)/);
  assert.match(runtime, /metadata\.iFrameRegExp/);
  assert.match(runtime, /if \(!iframeAllowed\(\)\) return/);
});

test('generated pinned IDLIX compatibility adapter has all runtime entrypoints', async () => {
  const paths = [
    '../extension/adapters/premid/idlix-legacy/presence.js',
    '../extension/adapters/premid/idlix-legacy/iframe.js',
    '../extension/adapters/premid/idlix-legacy/config.js',
  ];
  for (const path of paths) {
    const source = await readFile(new URL(path, import.meta.url), 'utf8');
    assert.ok(source.length > 20, `${path} should be generated by the pinned importer`);
  }
});
